import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const crateManifest = path.join(projectRoot, 'crates', 'gomoku-kernel', 'Cargo.toml');
const rawWasmPath = path.join(
  projectRoot,
  'crates',
  'gomoku-kernel',
  'target',
  'wasm32-unknown-unknown',
  'release',
  'gomoku_kernel.wasm'
);
const optWasmPath = path.join(
  projectRoot,
  'crates',
  'gomoku-kernel',
  'target',
  'wasm32-unknown-unknown',
  'release',
  'gomoku_kernel.opt.wasm'
);
const outputTsPath = path.join(
  projectRoot,
  'packages',
  'core',
  'src',
  'ai',
  'wasm',
  'kernelBinary.ts'
);

console.log('[build-wasm] Building Rust crate to wasm32-unknown-unknown (release)...');
execSync(`cargo build --manifest-path "${crateManifest}" --target wasm32-unknown-unknown --release`, {
  stdio: 'inherit',
  cwd: projectRoot,
});

if (!fs.existsSync(rawWasmPath)) {
  console.error(`[build-wasm] Error: Compiled wasm not found at ${rawWasmPath}`);
  process.exit(1);
}

const rawSize = fs.statSync(rawWasmPath).size;
console.log(`[build-wasm] Raw WASM binary built: ${rawSize} bytes`);

let finalWasmPath = rawWasmPath;
try {
  console.log('[build-wasm] Optimizing WASM with wasm-opt -Oz...');
  execSync(`wasm-opt --enable-bulk-memory -Oz "${rawWasmPath}" -o "${optWasmPath}"`, {
    stdio: 'inherit',
    cwd: projectRoot,
  });
  if (fs.existsSync(optWasmPath)) {
    const optSize = fs.statSync(optWasmPath).size;
    console.log(`[build-wasm] Optimized WASM: ${optSize} bytes (reduced by ${(100 - (optSize / rawSize) * 100).toFixed(1)}%)`);
    finalWasmPath = optWasmPath;
  }
} catch (err) {
  console.warn('[build-wasm] Warning: wasm-opt failed or not available; using unoptimized wasm binary.');
}

const wasmBytes = fs.readFileSync(finalWasmPath);
const base64String = wasmBytes.toString('base64');

const outputDir = path.dirname(outputTsPath);
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

const fileContent = `/**
 * Auto-generated by scripts/build-wasm.mjs.
 * DO NOT EDIT DIRECTLY.
 *
 * Inlined base64-encoded WebAssembly binary for Gomoku kernel evaluation.
 * Size: ${wasmBytes.length} bytes (raw binary).
 */
export const WASM_BASE64 = '${base64String}';
export const WASM_BYTE_LENGTH = ${wasmBytes.length};
`;

fs.writeFileSync(outputTsPath, fileContent, 'utf-8');
console.log(`[build-wasm] Inlined WASM base64 written to ${outputTsPath} (${base64String.length} chars)`);
